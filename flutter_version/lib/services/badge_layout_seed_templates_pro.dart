  final points = [
    BadgePathPoint(x: 0, y: 1.0),
    BadgePathPoint(x: 0, y: edgeY, outX: handle, outY: 0),
    BadgePathPoint(
      x: 0.16,
      y: midY,
      inX: -handle,
      inY: 0,
      outX: handle,
      outY: 0,
    ),
    BadgePathPoint(
      x: 0.84,
      y: midY,
      inX: -handle,
      inY: 0,
      outX: handle,
      outY: 0,
    ),
    BadgePathPoint(x: 1, y: edgeY, inX: -handle, inY: 0),
    BadgePathPoint(x: 1, y: 1.0),
  ];
  return BadgeElement(
    id: id,
    type: BadgeElementType.shape,
    x: x,
    y: y,
    width: w,
    height: h,
    shapeKind: BadgeShapeKind.path,
    pathPoints: points,
