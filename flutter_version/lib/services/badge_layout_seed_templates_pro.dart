/// Bande "vague" — un rectangle dont le bord inférieur (ou supérieur, si
/// [invert]) est une courbe bombée.
///
/// Poignées avec une composante VERTICALE — pas seulement horizontale.
/// Bug découvert en comparant au modèle de référence : avec des poignées
/// PUREMENT horizontales entre deux points à la MÊME hauteur, les 4
/// points de contrôle du segment cubique (ancre, poignée, poignée, ancre)
/// se retrouvent TOUS à la même hauteur — la courbe résultante est alors
/// une ligne PARFAITEMENT DROITE, pas une vague du tout (une propriété
/// des courbes de Bézier : 4 points de contrôle colinéaires ⇒ tracé
/// colinéaire, voir aussi la doc de `insertPathPoint`,
/// badge_builder_canvas.dart). `handleY` (composante verticale des
/// poignées, proportionnelle à [bulge]) corrige ça.
BadgeElement _waveBand({
  required String id,
  required double x,
  required double y,
  required double w,
  required double h,
  required double bulge, // fraction de h — amplitude de la vague
  int? fillColor,
  BadgeGradient? fillGradient,
  int zIndex = 0,
  bool invert = false, // true = vague vers le HAUT (bandeau du bas)
}) {
  final topY = invert ? bulge : 0.0;
  final bottomY = invert ? 1.0 : 1.0 - bulge;
  final handleY = (invert ? -bulge : bulge) * 0.55;
  final points = invert
      ? [
          BadgePathPoint(x: 0, y: 1),
          BadgePathPoint(x: 0, y: topY, outX: 0.28, outY: handleY),
          BadgePathPoint(x: 1, y: topY, inX: -0.28, inY: handleY),
          BadgePathPoint(x: 1, y: 1),
        ]
      : [
          BadgePathPoint(x: 0, y: 0),
          BadgePathPoint(x: 0, y: bottomY, outX: 0.28, outY: handleY),
          BadgePathPoint(x: 1, y: bottomY, inX: -0.28, inY: handleY),
          BadgePathPoint(x: 1, y: 0),
        ];
  return BadgeElement(
    id: id,
    type: BadgeElementType.shape,
    x: x,
    y: y,
    width: w,
    height: h,
    shapeKind: BadgeShapeKind.path,
    pathPoints: points,
    pathClosed: true,
    fillColor: fillColor,
    fillGradient: fillGradient,
    zIndex: zIndex,
  );
}

/// Bande à bord ondulé, un vrai CREUX central lisse et ARRONDI (pas
/// seulement un léger bombement comme [_waveBand], mais surtout pas un
/// "V" pointu) — pour "nicher" un élément (ex. la photo du modèle 1)
/// exactement sur le point le plus bas du creux. [edgeDepth]/[dipDepth]
/// en fraction de la hauteur de la bande (bord gauche/droit à
/// [edgeDepth], creux central à [dipDepth] — [dipDepth] > [edgeDepth]
/// pour un creux qui va VERS LE BAS en mode normal).
///
/// Poignées HORIZONTALES aux ancres de bord ET au creux central — comme
/// une transition "ease-in-ease-out" (CSS) : la tangente reste HORIZONTALE
/// aux deux extrémités de chaque demi-segment, pour que la vague reste
/// plate près des bords puis plonge, plutôt qu'une pente constante.
/// **Deuxième bug corrigé** après retour visuel sur l'image de référence :
/// un premier essai alignait les poignées sur la CORDE directe vers le
/// creux (même angle que la pente moyenne) — ça évite bien un coin vif à
/// CHAQUE point pris isolément, mais donne une pente quasi CONSTANTE sur
/// tout le segment, donc un "V" à coins arrondis, pas une vraie vallée
/// lisse. Contrairement au bug initial (poignées purement horizontales
/// entre deux points de MÊME hauteur, [_waveBand], qui dégénère en ligne
/// plate), ici les deux points d'un demi-segment sont à des hauteurs
/// DIFFÉRENTES : des poignées horizontales aux deux bouts ne dégénèrent
/// donc jamais en ligne droite, elles créent un véritable "S" doux.
///
/// **Magnitudes de poignée (0.25/0.25) vérifiées par un rendu réel** —
/// pas seulement par le calcul : un premier réglage (0.32/0.22,
/// asymétrique) produisait une ligne quasi plate loin du centre avec un
/// changement de pente visible juste avant le creux ("épaules" pointues
/// encadrant la photo). Faute d'affichage dans cet environnement pour
/// vérifier le rendu Flutter réel, la géométrie exacte (mêmes points,
/// mêmes poignées) a été reproduite avec Pillow (`python3`) et inspectée
/// directement comme image avant d'être choisie — voir le script
/// conservé dans le scratchpad de session au moment de ce correctif.
BadgeElement _scallopedBand({
  required String id,
  required double x,
  required double y,
  required double w,
  required double h,
  double edgeDepth = 0.3,
  double dipDepth = 0.62,
  int? fillColor,
  int zIndex = 0,
  bool invert = false,
}) {
  final ey = invert ? 1 - edgeDepth : edgeDepth;
  final dy = invert ? 1 - dipDepth : dipDepth;
  const edgeHandle = 0.25;
  const dipHandle = 0.25;
  final points = [
    BadgePathPoint(x: 0, y: invert ? 1.0 : 0.0),
    BadgePathPoint(x: 0, y: ey, outX: edgeHandle, outY: 0),
    BadgePathPoint(
      x: 0.5,
      y: dy,
      inX: -dipHandle,
      inY: 0,
      outX: dipHandle,
      outY: 0,
    ),
    BadgePathPoint(x: 1, y: ey, inX: -edgeHandle, inY: 0),
    BadgePathPoint(x: 1, y: invert ? 1.0 : 0.0),
  ];
  return BadgeElement(
    id: id,
    type: BadgeElementType.shape,
    x: x,
    y: y,
    width: w,
    height: h,
    shapeKind: BadgeShapeKind.path,
    pathPoints: points,
    pathClosed: true,
    fillColor: fillColor,
    zIndex: zIndex,
  );
}

/// Fin trait clair qui ÉPOUSE la même courbe que [_scallopedBand] mais EN
/// RETRAIT (edge/dip légèrement plus profonds, largeur resserrée) — un
/// tracé OUVERT (`pathClosed: false`, donc jamais rempli, seulement
/// tracé — voir `badge_layout_renderer.dart::_drawShape`,
/// `isOpenPath`). Repéré en comparant directement au modèle de
/// référence : le bandeau navy n'est pas seul, une ligne fine le "suit"
/// juste en dessous dans le blanc — absente de la toute première
/// reproduction.
BadgeElement _scallopedEcho({
  required String id,
  required double x,
  required double y,
  required double w,
  required double h,
  required double edgeDepth,
  required double dipDepth,
  int strokeColor = 0xFFFFFFFF,
  double strokeWidth = 2.5,
  int zIndex = -10,
}) {
  const handle = 0.25;
  final points = [
    BadgePathPoint(x: 0.06, y: edgeDepth, outX: handle, outY: 0),
    BadgePathPoint(
      x: 0.5,
      y: dipDepth,
      inX: -handle,
      inY: 0,
      outX: handle,
      outY: 0,
    ),
    BadgePathPoint(x: 0.94, y: edgeDepth, inX: -handle, inY: 0),
  ];
  return BadgeElement(
    id: id,
    type: BadgeElementType.shape,
    x: x,
    y: y,
    width: w,
    height: h,
    shapeKind: BadgeShapeKind.path,
    pathPoints: points,
    pathClosed: false,
    strokeColor: strokeColor,
    strokeWidth: strokeWidth,
    zIndex: zIndex,
  );
}

